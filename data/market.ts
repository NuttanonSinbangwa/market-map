const STALL_W = 92;
const STALL_H = 78;
const GAP = 6;

type Def = [
  name: string,
  products: string[],
  opts?: {
    cat?: CategoryId;
    hours?: [string, string];
    closedDays?: number[];
    note?: string;
  },
];

function build(zoneId: string, defaultCat: CategoryId, defs: Def[]): Stall[] {
  const zone = ZONES.find((z) => z.id === zoneId)!;
  return defs.map(([name, products, opts], i) => {
    const row = Math.floor(i / 5);
    const col = i % 5;
    return {
      id: `${zone.id}${String(i + 1).padStart(2, '0')}`,
      zone: zone.id,
      name,
      category: opts?.cat ?? defaultCat,
      products,
      hours: opts?.hours,
      closedDays: opts?.closedDays,
      note: opts?.note,
      x: zone.x + 18 + col * (STALL_W + GAP),
      y: zone.y + (row === 0 ? 44 : 150),
      w: STALL_W,
      h: STALL_H,
    };
  });
}

